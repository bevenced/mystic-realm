/**
 * Find the month number (1-12, BaZi month) for a given date.
 * Month 1 starts at 立春 (Li Chun), Month 2 at 惊蛰 (Jing Zhe), etc.
 */
export function getBaZiMonth(date: Date): number {
  const year = date.getFullYear();
  const mon = date.getMonth() + 1; // JS month is 0-based
  const day = date.getDate();
  const hour = date.getHours();

  // Get the appropriate solar term table entry, preferring same year
  // but falling back to previous year for dates before 立春
  let terms = SOLAR_TERMS[year];
  if (!terms) {
    // Approximate: use previous known year
    const keys = Object.keys(SOLAR_TERMS).map(Number);
    const nearest = keys.reduce((a, b) => Math.abs(a - year) < Math.abs(b - year) ? a : b);
    terms = SOLAR_TERMS[nearest];
  }

  // Index 0 = 立春 (Month 1 start), through index 11 = 小寒 (Month 12 start)
  // Each entry is [month, day, hour]
  for (let i = 0; i < terms.length; i++) {
    const [termMon, termDay, termHour] = terms[i];
    if (mon < termMon || (mon === termMon && (day < termDay || (day === termDay && hour < termHour)))) {
      // We're before this term, so we're in the previous month
      if (i === 0) {
        // Before 立春 = still in month 12 of previous year
        return 12;
      }
      return i; // Month i starts at terms[i-1], so we're still in month i
    }
  }

  // After 小寒 = still in month 12
  return 12;
}

/**
 * Get the Jie (节) date for a given BaZi month and year.
 * Returns [month, day, hour] of the Jie that starts the month.
 */
export function getJieDate(year: number, baziMonth: number): Date | null {
  const terms = SOLAR_TERMS[year] || SOLAR_TERMS[Object.keys(SOLAR_TERMS).map(Number).reduce((a, b) =>
    Math.abs(a - year) < Math.abs(b - year) ? a : b
  )];

  if (!terms || baziMonth < 1 || baziMonth > 12) return null;

  const idx = baziMonth - 1; // Month 1 = index 0 (立春)
  const [mon, day, hour] = terms[idx];

  // If the Jie falls in month 1 of the next calendar year (小寒 = Jan 6-ish)
  const actualYear = mon === 1 && baziMonth === 12 ? year : year;
  return new Date(actualYear, mon - 1, day, hour);
}

/**
 * Get the previous Jie (节) from a given date.
 * Used for Da Yun starting age calculation.
 */
export function getPreviousJie(date: Date): { jie: string; date: Date } {
  const year = date.getFullYear();
  const mon = date.getMonth() + 1;
  const day = date.getDate();

  // Try this year's terms
  let terms = SOLAR_TERMS[year];
  if (!terms) {
    const keys = Object.keys(SOLAR_TERMS).map(Number);
    const nearest = keys.reduce((a, b) => Math.abs(a - year) < Math.abs(b - year) ? a : b);
    terms = SOLAR_TERMS[nearest];
  }

  const dateTs = date.getTime();

  // Check each Jie in reverse order
  for (let i = terms.length - 1; i >= 0; i--) {
    const [m, d, h] = terms[i];
    const jieDate = new Date(m === 1 && i >= 11 ? year : year, m - 1, d, h);
    // Adjust year for 小寒 (which is in January but belongs to previous year's month 12)
    if (i >= 11) {
      jieDate.setFullYear(year);
    }
    if (jieDate.getTime() <= dateTs) {
      return { jie: JIE_NAMES[i], date: jieDate };
    }
  }

  // Try previous year
  const prevTerms = SOLAR_TERMS[year - 1] || terms;
  for (let i = prevTerms.length - 1; i >= 0; i--) {
    const [m, d, h] = prevTerms[i];
    const jieDate = new Date(year - 1, m - 1, d, h);
    if (jieDate.getTime() <= dateTs) {
      return { jie: JIE_NAMES[i], date: jieDate };
    }
  }

  return { jie: "立春", date: new Date(year, 1, 4) };
}

/**
 * Get the next Jie (节) from a given date.
 */
export function getNextJie(date: Date): { jie: string; date: Date } {
  const year = date.getFullYear();
  let terms = SOLAR_TERMS[year];
  if (!terms) {
    const keys = Object.keys(SOLAR_TERMS).map(Number);
    const nearest = keys.reduce((a, b) => Math.abs(a - year) < Math.abs(b - year) ? a : b);
    terms = SOLAR_TERMS[nearest];
  }

  const dateTs = date.getTime();

  for (let i = 0; i < terms.length; i++) {
    const [m, d, h] = terms[i];
    const targetYear = m === 1 && i === 0 ? year + 1 :
                       m === 1 && i >= 11 ? year :
                       i === 0 ? year : year;
    const jieDate = new Date(targetYear, m - 1, d, h);
    if (jieDate.getTime() > dateTs) {
      return { jie: JIE_NAMES[i], date: jieDate };
    }
  }

  // Next year's 立春
  const nextYear = year + 1;
  const nextTerms = SOLAR_TERMS[nextYear] || terms;
  const [m, d, h] = nextTerms[0];
  return { jie: JIE_NAMES[0], date: new Date(nextYear, m - 1, d, h) };
}
